import { debounce } from "@/assets/scripts/utility/config/debounce";

const interfaceSlider = document.getElementById("interface-slider");
const fecharInterface = document.getElementById("back-to-area");
const iconeExibido = document.getElementById("icone-exibido-img");
const tituloExibido = document.getElementById("titulo-icone-exibido"); 
const releaseExibida = document.getElementById("release-icone-exibido");
const categoriaExibida = document.getElementById("categoria-icone-exibido");
const tagsExibidas = document.getElementById("container-tags-exibidas");
const linkExibido = document.getElementById("link-icone-exibido");
const botaoCopiar = document.getElementById("copy-link-icon");
const icone = botaoCopiar.querySelector("i");
const baixarPNG = document.getElementById("baixar-png-icone");
const baixarSVG = document.getElementById("baixar-svg-icone");

let interfaceVisivel = false;
let controladorEventos = null;

fecharInterface.addEventListener("click", MoverInterface);

const resetarIcone = debounce(() => {
  icone.className = "fa-solid fa-copy";
}, 1500);

export function ExibirIcone(id, icones_dic){
    MoverInterface();
    tagsExibidas.innerHTML = "";
    const chave = icones_dic.get(id);
    const textoParaCopiar = `<i class="ttt-${chave.id}"></i>`;
    iconeExibido.innerHTML = textoParaCopiar;
    tituloExibido.textContent = chave.name;
    categoriaExibida.textContent = chave.category;
    releaseExibida.textContent = `Released: ${chave.release}`;
    linkExibido.textContent = textoParaCopiar;
    chave.tags.forEach(tag => {
      tagsExibidas.innerHTML += `
                <p class="balao-sem-cor">${tag}</p>`;
    });

    if(controladorEventos)
      controladorEventos.abort();
    
    controladorEventos = new AbortController();
    const { signal } = controladorEventos;

    botaoCopiar.addEventListener("click", () => {
        navigator.clipboard.writeText(textoParaCopiar).then(() => {
            icone.className = "fa-regular fa-copy";

            resetarIcone();
        });
    }, { signal });
    baixarPNG.addEventListener("click", () =>{
        BaixarPNG(chave.id, icones_dic);
    }, { signal });
    baixarSVG.addEventListener("click", () =>{
        BaixarSVG(chave.id, icones_dic);
    }, { signal });
}

function MoverInterface() {
  interfaceVisivel = !interfaceVisivel;
  if (interfaceVisivel) {
    interfaceSlider.classList.add("deslocado");
  } else {
    interfaceSlider.classList.remove("deslocado");
  }
}

// 1. Adiciona um estado no histórico para capturar o recuo
history.pushState(null, "", location.href);

// 2. Intercepta o botão de VOLTAR (do navegador ou do mouse)
window.addEventListener("popstate", function () {
  history.pushState(null, "", location.href); // Impede que a página realmente volte
  MoverInterface();
});

// 3. Intercepta o movimento de AVANÇAR (quando a página é restaurada do cache)
window.addEventListener("pageshow", function (event) {
  if (event.persisted) {
    MoverInterface();
  }
});

export function BaixarSVG(id, icones_dic) {
  const chave = icones_dic.get(id);
  if (!chave || !chave.path) return;

  const svgContent = `
  <svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 640 640">
  <!-- 
    * Icon generated by Tap to Tool *
    https://taptotool.com/
    License: Free for personal and commercial use. 
    Redistribution, resale, or claiming ownership of this vector file is prohibited. 
    * Read more: https://taptotool.com/legal/terms/ 
  -->
  <path fill="currentColor" d="${chave.path}"/>
</svg>`;

  const blob = new Blob([svgContent], { type: "image/svg+xml;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  
  const link = document.createElement("a");
  link.href = url;
  link.download = `${chave.id}.svg`;
  document.body.appendChild(link);
  link.click();
  
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

export function BaixarPNG(id, icones_dic, tamanho = 640) {
  const chave = icones_dic.get(id);
  if (!chave || !chave.path) return;

  const svgString = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 640 640" width="${tamanho}" height="${tamanho}">
    <path d="${chave.path}" fill="#000000"/>
  </svg>`;

  const blob = new Blob([svgString], { type: "image/svg+xml;charset=utf-8" });
  const url = URL.createObjectURL(blob);

  const img = new Image();
  img.onload = () => {
    const canvas = document.createElement("canvas");
    canvas.width = tamanho;
    canvas.height = tamanho;
    const ctx = canvas.getContext("2d");
    
    ctx.drawImage(img, 0, 0);

    const pngUrl = canvas.toDataURL("image/png");
    const link = document.createElement("a");
    link.href = pngUrl;
    link.download = `${chave.id}.png`;
    document.body.appendChild(link);
    link.click();

    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };

  img.src = url;
}

